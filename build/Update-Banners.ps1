#Requires -Version 5.1

<#
.SYNOPSIS
Generates the shared project-banner layout from repository branding data.
.PARAMETER Check
Checks that both committed banners match the generated bytes without writing files.
#>
[CmdletBinding()]
param(
    [switch]$Check
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$Brand = Get-Content -LiteralPath (Join-Path $Root 'assets\branding.json') -Raw | ConvertFrom-Json
$Scripts = @(Get-ChildItem -LiteralPath (Join-Path $Root 'Scripts') -Filter '*.ps1' -File)
if ($Scripts.Count -ne 1 -or $Brand.script -cne $Scripts[0].Name) {
    throw 'Branding must name the single deployment script without a directory prefix.'
}
if (@($Brand.compactTitle).Count -ne 2) {
    throw 'Branding must supply exactly two compact title lines.'
}
foreach ($Value in @($Brand.title, $Brand.subtitle, $Brand.compactSubtitle,
        $Brand.script, $Brand.description) + @($Brand.compactTitle)) {
    if ([string]::IsNullOrWhiteSpace($Value)) {
        throw 'Branding text must not be empty.'
    }
}

$Template = @'
<svg xmlns="http://www.w3.org/2000/svg" width="{{width}}" height="360" viewBox="0 0 {{width}} 360" role="img" aria-labelledby="title desc">
  <title id="title">{{title}}</title>
  <desc id="desc">{{description}}</desc>
  <style>
    svg { color-scheme: light dark; font-family: "Segoe UI", Arial, sans-serif; }
    .start { stop-color: #155799; }
    .end { stop-color: #117865; }
    text { fill: #ffffff; }
    .script-name { font-family: Consolas, "Cascadia Mono", monospace; }
    @media (prefers-color-scheme: dark) {
      .start { stop-color: #0d2e4c; }
      .end { stop-color: #103d38; }
    }
  </style>
  <defs>
    <linearGradient id="background" x1="0" x2="1" y1="0" y2="1">
      <stop class="start" offset="0"/>
      <stop class="end" offset="1"/>
    </linearGradient>
  </defs>
  <rect width="{{width}}" height="360" rx="24" fill="url(#background)"/>
{{lines}}
</svg>
'@

$Encoding = New-Object Text.UTF8Encoding($false)
foreach ($Variant in @(
        @{ Name = 'banner.svg'; Width = 1280; Compact = $false },
        @{ Name = 'banner-compact.svg'; Width = 640; Compact = $true }
    )) {
    if ($Variant.Compact) {
        $Lines = @(
            '<text x="32" y="48" font-size="22" font-weight="600">VARTAXE / CONFIGMGR OSD</text>',
            ('<text x="32" y="114" font-size="44" font-weight="700">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.compactTitle[0])),
            ('<text x="32" y="167" font-size="44" font-weight="700">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.compactTitle[1])),
            ('<text x="32" y="216" font-size="25">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.compactSubtitle)),
            ('<text class="script-name" x="32" y="270" font-size="24">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.script)),
            '<text x="32" y="326" font-size="24">Windows PowerShell 5.1 / MIT licensed</text>'
        )
    }
    else {
        $Lines = @(
            '<text x="64" y="68" font-size="24" font-weight="600">VARTAXE / CONFIGMGR OSD</text>',
            ('<text x="64" y="150" font-size="52" font-weight="700">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.title)),
            ('<text x="64" y="208" font-size="28">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.subtitle)),
            ('<text class="script-name" x="64" y="263" font-size="24">{0}</text>' -f [Security.SecurityElement]::Escape($Brand.script)),
            '<text x="64" y="318" font-size="24">Windows PowerShell 5.1 / MIT licensed</text>'
        )
    }
    $Content = $Template.Replace('{{width}}', [string]$Variant.Width).
        Replace('{{title}}', [Security.SecurityElement]::Escape($Brand.title)).
        Replace('{{description}}', [Security.SecurityElement]::Escape($Brand.description)).
        Replace('{{lines}}', (($Lines | ForEach-Object { '  ' + $_ }) -join "`n"))
    $Content = $Content.Replace("`r`n", "`n").TrimEnd("`r", "`n") + "`n"
    $Path = Join-Path $Root ('assets\' + $Variant.Name)
    if ($Check) {
        if (-not (Test-Path -LiteralPath $Path -PathType Leaf) -or
            [Convert]::ToBase64String([IO.File]::ReadAllBytes($Path)) -cne
            [Convert]::ToBase64String($Encoding.GetBytes($Content))) {
            throw "Banner is out of date: $($Variant.Name). Run build\Update-Banners.ps1."
        }
    }
    else {
        [IO.File]::WriteAllText($Path, $Content, $Encoding)
    }
}
Write-Output 'Both project banners match the shared layout.'
